import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { createIdentity } from "../src/services/auth.ts";

const database = new DatabaseSync(":memory:");
const auth = createIdentity(
  database,
  "schema-generation-only-secret-32-characters",
  "http://127.0.0.1:8787",
  async () => {},
);
const plan = await getMigrations(auth.options);
const sql = `-- Generated by better-auth 1.7.27 getMigrations(createIdentity(...).options). Do not edit.\n${await plan.compileMigrations()}\n`;
const path = "migrations/0003_better_auth.sql";
if (process.argv.includes("--check"))
  assert.equal(
    readFileSync(path, "utf8"),
    sql,
    "Auth schema drift: review a new append-only migration",
  );
else writeFileSync(path, sql);
database.close();
console.log("Pinned Better Auth schema verified.");
